-- A failed launch is demonstrated inside a savepoint so the script can continue.
SAVEPOINT invalid_launch_test;

DO $$
BEGIN
    BEGIN
        INSERT INTO instances
            (instance_id, instance_type_id, image_id, instance_state, environment)
        SELECT
            'i-invalid-architecture',
            t.instance_type_id,
            'img-arm-stable',
            'running',
            'test'
        FROM instance_types AS t
        WHERE t.type_name = 'general.medium';

        RAISE EXCEPTION 'Expected architecture policy to reject the insert';
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLERRM = 'Expected architecture policy to reject the insert' THEN
                RAISE;
            END IF;
            RAISE NOTICE 'Invalid architecture launch rejected: %', SQLERRM;
    END;
END;
$$;

ROLLBACK TO SAVEPOINT invalid_launch_test;
RELEASE SAVEPOINT invalid_launch_test;

-- Direct capacity and monthly-cost inventory.
SELECT
    family_code,
    COUNT(*) AS instance_type_count,
    SUM(vcpus) AS catalog_vcpu_total,
    SUM(memory_gib) AS catalog_memory_gib_total,
    ROUND(MIN(hourly_rate_usd), 4) AS lowest_hourly_rate,
    ROUND(MAX(hourly_rate_usd), 4) AS highest_hourly_rate
FROM instance_types
WHERE available
GROUP BY family_code
ORDER BY family_code;

