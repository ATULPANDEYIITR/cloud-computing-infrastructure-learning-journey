CREATE TABLE IF NOT EXISTS instance_families (
    family_code TEXT PRIMARY KEY,
    family_name TEXT NOT NULL,
    intended_workload TEXT NOT NULL,
    description TEXT NOT NULL,
    CHECK (family_code ~ '^[a-z][a-z0-9_]*$')
);

CREATE TABLE IF NOT EXISTS instance_types (
    instance_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name TEXT NOT NULL UNIQUE,
    family_code TEXT NOT NULL REFERENCES instance_families(family_code),
    vcpus INTEGER NOT NULL CHECK (vcpus > 0),
    memory_gib NUMERIC(8,2) NOT NULL CHECK (memory_gib > 0),
    architecture TEXT NOT NULL CHECK (architecture IN ('x86_64', 'arm64')),
    network_gbps NUMERIC(8,2) NOT NULL CHECK (network_gbps > 0),
    hourly_rate_usd NUMERIC(12,6) NOT NULL CHECK (hourly_rate_usd >= 0),
    is_burstable BOOLEAN NOT NULL DEFAULT FALSE,
    available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS machine_images (
    image_id TEXT PRIMARY KEY,
    image_name TEXT NOT NULL,
    operating_system TEXT NOT NULL,
    architecture TEXT NOT NULL CHECK (architecture IN ('x86_64', 'arm64')),
    root_disk_gib INTEGER NOT NULL CHECK (root_disk_gib >= 8),
    owner_name TEXT NOT NULL,
    trusted BOOLEAN NOT NULL DEFAULT FALSE,
    encrypted BOOLEAN NOT NULL DEFAULT FALSE,
    image_status TEXT NOT NULL DEFAULT 'available'
        CHECK (image_status IN ('available', 'deprecated', 'revoked')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(trim(image_name)) > 0),
    CHECK (length(trim(owner_name)) > 0)
);

CREATE TABLE IF NOT EXISTS workloads (
    workload_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_name TEXT NOT NULL,
    workload_class TEXT NOT NULL
        CHECK (workload_class IN ('general', 'web', 'compute', 'memory')),
    required_vcpus INTEGER NOT NULL CHECK (required_vcpus > 0),
    required_memory_gib NUMERIC(8,2) NOT NULL
        CHECK (required_memory_gib > 0),
    minimum_network_gbps NUMERIC(8,2) NOT NULL DEFAULT 0.5
        CHECK (minimum_network_gbps >= 0),
    required_architecture TEXT NOT NULL
        CHECK (required_architecture IN ('x86_64', 'arm64')),
    allow_burstable BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(trim(workload_name)) > 0)
);

CREATE TABLE IF NOT EXISTS instances (
    instance_id TEXT PRIMARY KEY,
    instance_type_id BIGINT NOT NULL REFERENCES instance_types(instance_type_id),
    image_id TEXT NOT NULL REFERENCES machine_images(image_id),
    workload_id BIGINT REFERENCES workloads(workload_id),
    instance_state TEXT NOT NULL DEFAULT 'stopped'
        CHECK (instance_state IN ('stopped', 'running', 'terminated')),
    environment TEXT NOT NULL DEFAULT 'development',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    state_changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    terminated_at TIMESTAMPTZ,
    CHECK (
        (instance_state = 'terminated' AND terminated_at IS NOT NULL)
        OR
        (instance_state <> 'terminated' AND terminated_at IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS instance_state_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id TEXT NOT NULL REFERENCES instances(instance_id),
    previous_state TEXT,
    new_state TEXT NOT NULL
        CHECK (new_state IN ('stopped', 'running', 'terminated')),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason TEXT NOT NULL
);

