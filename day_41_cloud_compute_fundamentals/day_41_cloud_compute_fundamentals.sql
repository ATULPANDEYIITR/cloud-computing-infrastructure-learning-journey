-- Candidate selection enforces workload, architecture, CPU, memory, network,
-- burstability, and image compatibility in the relational query.
CREATE OR REPLACE VIEW workload_instance_candidates AS
SELECT
    w.workload_id,
    w.workload_name,
    t.instance_type_id,
    t.type_name,
    t.family_code,
    t.vcpus,
    t.memory_gib,
    t.architecture,
    t.network_gbps,
    t.hourly_rate_usd,
    ROUND(t.hourly_rate_usd * 24 * 30, 2) AS monthly_compute_usd,
    i.image_id,
    i.image_name
FROM workloads AS w
JOIN instance_types AS t
  ON t.available
 AND t.architecture = w.required_architecture
 AND t.vcpus >= w.required_vcpus
 AND t.memory_gib >= w.required_memory_gib
 AND t.network_gbps >= w.minimum_network_gbps
 AND (NOT t.is_burstable OR w.allow_burstable)
JOIN machine_images AS i
  ON i.architecture = t.architecture
 AND i.image_status = 'available'
 AND i.trusted
 AND i.encrypted;

-- Candidate ranking is per workload. A cheapest option is not necessarily the
-- best production choice if sustained CPU, storage, or latency differ.
SELECT
    workload_name,
    type_name,
    vcpus,
    memory_gib,
    architecture,
    network_gbps,
    hourly_rate_usd,
    monthly_compute_usd,
    image_id
FROM (
    SELECT
        c.*,
        ROW_NUMBER() OVER (
            PARTITION BY workload_id
            ORDER BY hourly_rate_usd, memory_gib, vcpus
        ) AS price_rank
    FROM workload_instance_candidates AS c
) AS ranked
WHERE price_rank <= 3
ORDER BY workload_name, price_rank;

-- Estimate workload packing using reserved CPU and memory headroom.
WITH assumptions AS (
    SELECT
        t.type_name,
        t.vcpus * 0.90 AS usable_vcpus,
        t.memory_gib - 0.5 AS usable_memory_gib,
        2::NUMERIC AS workload_vcpus,
        3::NUMERIC AS workload_memory_gib
    FROM instance_types AS t
    WHERE t.type_name = 'compute.large'
)
SELECT
    type_name,
    usable_vcpus,
    usable_memory_gib,
    CASE
        WHEN usable_vcpus < workload_vcpus
          OR usable_memory_gib < workload_memory_gib THEN 0
        ELSE LEAST(
            FLOOR(usable_vcpus / workload_vcpus),
            FLOOR(usable_memory_gib / workload_memory_gib)
        )::INTEGER
    END AS estimated_workload_placements
FROM assumptions;

-- Database trigger enforcement ensures invalid image/type combinations cannot
-- be persisted as running instances even if application validation is skipped.
CREATE OR REPLACE FUNCTION enforce_instance_launch_policy()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    selected_architecture TEXT;
    image_architecture TEXT;
    image_trusted BOOLEAN;
    image_encrypted BOOLEAN;
    image_status_value TEXT;
    instance_available BOOLEAN;
BEGIN
    IF NEW.instance_state = 'running'
       AND (
           TG_OP = 'INSERT'
           OR OLD.instance_state IS DISTINCT FROM NEW.instance_state
           OR OLD.instance_type_id IS DISTINCT FROM NEW.instance_type_id
           OR OLD.image_id IS DISTINCT FROM NEW.image_id
       )
    THEN
        SELECT architecture, available
        INTO selected_architecture, instance_available
        FROM instance_types
        WHERE instance_type_id = NEW.instance_type_id
        FOR SHARE;

        IF NOT FOUND OR NOT instance_available THEN
            RAISE EXCEPTION 'Instance type is unavailable';
        END IF;

        SELECT architecture, trusted, encrypted, image_status
        INTO image_architecture, image_trusted, image_encrypted, image_status_value
        FROM machine_images
        WHERE image_id = NEW.image_id
        FOR SHARE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Machine image does not exist';
        END IF;

        IF selected_architecture <> image_architecture THEN
            RAISE EXCEPTION 'Image and instance architectures do not match';
        END IF;

        IF NOT image_trusted OR NOT image_encrypted
           OR image_status_value <> 'available' THEN
            RAISE EXCEPTION 'Machine image does not meet launch policy';
        END IF;
    END IF;

    IF TG_OP = 'UPDATE'
       AND OLD.instance_state = 'terminated'
       AND NEW.instance_state <> 'terminated' THEN
        RAISE EXCEPTION 'Terminated instances cannot be restarted';
    END IF;

    IF NEW.instance_state = 'terminated' THEN
        NEW.terminated_at := COALESCE(NEW.terminated_at, CURRENT_TIMESTAMP);
    ELSE
        NEW.terminated_at := NULL;
    END IF;

    IF TG_OP = 'INSERT'
       OR OLD.instance_state IS DISTINCT FROM NEW.instance_state THEN
        NEW.state_changed_at := CURRENT_TIMESTAMP;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_instance_launch_policy ON instances;

CREATE TRIGGER trg_instance_launch_policy
BEFORE INSERT OR UPDATE OF instance_state, instance_type_id, image_id
ON instances
FOR EACH ROW
EXECUTE FUNCTION enforce_instance_launch_policy();

CREATE OR REPLACE FUNCTION record_instance_state_event()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO instance_state_events
            (instance_id, previous_state, new_state, reason)
        VALUES
            (NEW.instance_id, NULL, NEW.instance_state, 'Instance registered');
    ELSIF OLD.instance_state IS DISTINCT FROM NEW.instance_state THEN
        INSERT INTO instance_state_events
            (instance_id, previous_state, new_state, reason)
        VALUES
            (NEW.instance_id, OLD.instance_state, NEW.instance_state,
             'Instance state transition');
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_record_instance_state_event ON instances;

CREATE TRIGGER trg_record_instance_state_event
AFTER INSERT OR UPDATE OF instance_state ON instances
FOR EACH ROW
EXECUTE FUNCTION record_instance_state_event();

