/*
 * DATABASE HIGH AVAILABILITY
 * Multi-zone active-passive cluster, replica eligibility, fencing,
 * quorum validation, promotion, and failover auditing.
 *
 * Compatible with PostgreSQL 14+.
 *
 * The script resets the dedicated "ha" schema. Do not run it in a database
 * containing application objects that must be preserved in that schema.
 *
 * This relational model records control-plane state. It does not configure
 * PostgreSQL streaming replication, create physical replicas, or perform
 * cloud infrastructure fencing.
 */

DROP SCHEMA IF EXISTS ha CASCADE;
CREATE SCHEMA ha;

SET search_path = ha, public;

CREATE TYPE ha.node_role AS ENUM (
    'primary',
    'replica'
);

CREATE TYPE ha.health_status AS ENUM (
    'healthy',
    'degraded',
    'unreachable',
    'unknown'
);

CREATE TYPE ha.replication_mode AS ENUM (
    'synchronous',
    'asynchronous'
);

-- A cluster represents one logical database service.
-- The primary pointer is added after the node table is created.
CREATE TABLE ha.clusters (
    cluster_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_name            VARCHAR(120) NOT NULL UNIQUE,
    expected_voters         INTEGER NOT NULL CHECK (expected_voters > 0),
    current_primary_node_id BIGINT,
    cluster_epoch           BIGINT NOT NULL DEFAULT 1 CHECK (cluster_epoch > 0),
    fencing_token           BIGINT NOT NULL DEFAULT 1 CHECK (fencing_token >= 0),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Node identity and membership are stable. Replication lag and role are
-- operational attributes that change as the cluster evolves.
CREATE TABLE ha.database_nodes (
    node_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_id          BIGINT NOT NULL
                        REFERENCES ha.clusters(cluster_id) ON DELETE CASCADE,
    node_name           VARCHAR(120) NOT NULL,
    availability_zone   VARCHAR(120) NOT NULL,
    role                ha.node_role NOT NULL,
    voting_member       BOOLEAN NOT NULL DEFAULT TRUE,
    replication_mode    ha.replication_mode NOT NULL,
    replication_lag_ms  INTEGER NOT NULL DEFAULT 0
                        CHECK (replication_lag_ms >= 0),
    fenced              BOOLEAN NOT NULL DEFAULT FALSE,
    fencing_token       BIGINT NOT NULL DEFAULT 0
                        CHECK (fencing_token >= 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_node_cluster_id UNIQUE (cluster_id, node_id),
    CONSTRAINT uq_node_name_per_cluster UNIQUE (cluster_id, node_name)
);

-- The composite foreign key prevents a cluster from identifying a primary
-- node belonging to another cluster. Deferral supports atomic promotion.
ALTER TABLE ha.clusters
    ADD CONSTRAINT fk_cluster_current_primary
    FOREIGN KEY (cluster_id, current_primary_node_id)
    REFERENCES ha.database_nodes (cluster_id, node_id)
    DEFERRABLE INITIALLY DEFERRED;

-- Database-level protection against two primary nodes in one cluster.
CREATE UNIQUE INDEX uq_one_primary_per_cluster
    ON ha.database_nodes (cluster_id)
    WHERE role = 'primary';

CREATE INDEX ix_nodes_cluster_role
    ON ha.database_nodes (cluster_id, role);

CREATE INDEX ix_nodes_voting_members
    ON ha.database_nodes (cluster_id, node_id)
    WHERE voting_member = TRUE;

-- Policy is stored independently from node health and replication state.
-- This allows governance rules to change without rewriting observations.
CREATE TABLE ha.failover_policies (
    policy_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_id                  BIGINT NOT NULL UNIQUE
                                REFERENCES ha.clusters(cluster_id)
                                ON DELETE CASCADE,
    quorum_required             INTEGER NOT NULL CHECK (quorum_required > 0),
    max_replication_lag_ms      INTEGER NOT NULL
                                CHECK (max_replication_lag_ms >= 0),
    require_synchronous_replica BOOLEAN NOT NULL DEFAULT TRUE,
    require_old_primary_fenced  BOOLEAN NOT NULL DEFAULT TRUE,
    max_health_age              INTERVAL NOT NULL
                                CHECK (max_health_age > INTERVAL '0 seconds'),
    minimum_availability_zones  INTEGER NOT NULL DEFAULT 2
                                CHECK (minimum_availability_zones >= 2),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Health is append-only history. A current-state view selects the latest
-- observation instead of overwriting evidence from previous probes.
CREATE TABLE ha.health_observations (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_id     BIGINT NOT NULL,
    node_id        BIGINT NOT NULL,
    health_status  ha.health_status NOT NULL,
    observed_at    TIMESTAMPTZ NOT NULL,
    observation_source VARCHAR(120) NOT NULL,
    details        JSONB NOT NULL DEFAULT '{}'::JSONB,

    CONSTRAINT fk_observation_node
        FOREIGN KEY (cluster_id, node_id)
        REFERENCES ha.database_nodes(cluster_id, node_id)
        ON DELETE CASCADE,

    CONSTRAINT ck_observation_source
        CHECK (length(trim(observation_source)) > 0)
);

CREATE INDEX ix_health_observation_latest
    ON ha.health_observations (node_id, observed_at DESC, observation_id DESC);

CREATE OR REPLACE VIEW ha.latest_node_health AS
SELECT DISTINCT ON (cluster_id, node_id)
    cluster_id,
    node_id,
    health_status,
    observed_at,
    observation_source,
    details
FROM ha.health_observations
ORDER BY cluster_id, node_id, observed_at DESC, observation_id DESC;

-- The event log records transitions, not just the latest primary pointer.
CREATE TABLE ha.failover_events (
    event_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_id           BIGINT NOT NULL
                         REFERENCES ha.clusters(cluster_id) ON DELETE RESTRICT,
    old_primary_node_id  BIGINT,
    new_primary_node_id  BIGINT NOT NULL,
    previous_epoch       BIGINT NOT NULL,
    new_epoch            BIGINT NOT NULL,
    fencing_token        BIGINT NOT NULL,
    healthy_voters       INTEGER NOT NULL CHECK (healthy_voters >= 0),
    initiated_by         VARCHAR(160) NOT NULL,
    occurred_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_event_old_primary
        FOREIGN KEY (cluster_id, old_primary_node_id)
        REFERENCES ha.database_nodes(cluster_id, node_id),

    CONSTRAINT fk_event_new_primary
        FOREIGN KEY (cluster_id, new_primary_node_id)
        REFERENCES ha.database_nodes(cluster_id, node_id),

    CONSTRAINT ck_event_epoch
        CHECK (new_epoch > previous_epoch),

    CONSTRAINT ck_event_actor
        CHECK (length(trim(initiated_by)) > 0)
);

CREATE INDEX ix_failover_events_cluster_time
    ON ha.failover_events (cluster_id, occurred_at DESC);

-- Maintain updated_at consistently for mutable operational records.
CREATE OR REPLACE FUNCTION ha.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_cluster_updated_at
BEFORE UPDATE ON ha.clusters
FOR EACH ROW
EXECUTE FUNCTION ha.set_updated_at();

CREATE TRIGGER trg_node_updated_at
BEFORE UPDATE ON ha.database_nodes
FOR EACH ROW
EXECUTE FUNCTION ha.set_updated_at();

CREATE TRIGGER trg_policy_updated_at
BEFORE UPDATE ON ha.failover_policies
FOR EACH ROW
EXECUTE FUNCTION ha.set_updated_at();

-- A node cannot silently migrate between clusters. Membership changes
-- require an explicit removal and registration workflow.
CREATE OR REPLACE FUNCTION ha.prevent_node_membership_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.cluster_id <> OLD.cluster_id OR NEW.node_id <> OLD.node_id THEN
        RAISE EXCEPTION
            'Node identity and cluster membership are immutable';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_immutable_node_membership
BEFORE UPDATE ON ha.database_nodes
FOR EACH ROW
EXECUTE FUNCTION ha.prevent_node_membership_change();


/*
 * Eligibility checks are read-only.
 *
 * A candidate must be a healthy, fresh replica within the lag limit.
 * The current primary must be unhealthy or have stale health information.
 * If configured, the current primary must also be fenced.
 * Healthy voting members must meet the configured quorum.
 *
 * Each failed condition is returned as a reason rather than being hidden
 * behind a single boolean result.
 */
CREATE OR REPLACE FUNCTION ha.evaluate_failover(
    p_cluster_id BIGINT,
    p_candidate_node_id BIGINT
)
RETURNS TABLE (
    eligible BOOLEAN,
    reason TEXT,
    healthy_voters INTEGER,
    candidate_lag_ms INTEGER
)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_cluster           ha.clusters%ROWTYPE;
    v_policy            ha.failover_policies%ROWTYPE;
    v_candidate         ha.database_nodes%ROWTYPE;
    v_primary           ha.database_nodes%ROWTYPE;
    v_candidate_health ha.latest_node_health%ROWTYPE;
    v_primary_health   ha.latest_node_health%ROWTYPE;
    v_healthy_voters    INTEGER := 0;
    v_reasons           TEXT[] := ARRAY[]::TEXT[];
BEGIN
    SELECT *
    INTO v_cluster
    FROM ha.clusters
    WHERE cluster_id = p_cluster_id;

    IF NOT FOUND THEN
        RETURN QUERY
        SELECT FALSE, 'cluster_not_found'::TEXT, 0::INTEGER, NULL::INTEGER;
        RETURN;
    END IF;

    SELECT *
    INTO v_policy
    FROM ha.failover_policies
    WHERE cluster_id = p_cluster_id;

    IF NOT FOUND THEN
        RETURN QUERY
        SELECT FALSE, 'policy_not_found'::TEXT, 0::INTEGER, NULL::INTEGER;
        RETURN;
    END IF;

    SELECT *
    INTO v_candidate
    FROM ha.database_nodes
    WHERE cluster_id = p_cluster_id
      AND node_id = p_candidate_node_id;

    IF NOT FOUND THEN
        RETURN QUERY
        SELECT FALSE, 'candidate_not_found'::TEXT, 0::INTEGER, NULL::INTEGER;
        RETURN;
    END IF;

    IF v_candidate.role <> 'replica' THEN
        v_reasons := array_append(v_reasons, 'candidate_is_not_a_replica');
    END IF;

    IF v_candidate.node_id = v_cluster.current_primary_node_id THEN
        v_reasons := array_append(v_reasons, 'candidate_is_current_primary');
    END IF;

    SELECT *
    INTO v_candidate_health
    FROM ha.latest_node_health
    WHERE cluster_id = p_cluster_id
      AND node_id = p_candidate_node_id;

    IF NOT FOUND THEN
        v_reasons := array_append(v_reasons, 'candidate_has_no_health_observation');
    ELSE
        IF v_candidate_health.health_status <> 'healthy' THEN
            v_reasons := array_append(v_reasons, 'candidate_is_not_healthy');
        END IF;

        IF v_candidate_health.observed_at <
           now() - v_policy.max_health_age THEN
            v_reasons := array_append(
                v_reasons,
                'candidate_health_observation_is_stale'
            );
        END IF;
    END IF;

    IF v_policy.require_synchronous_replica
       AND v_candidate.replication_mode <> 'synchronous' THEN
        v_reasons := array_append(v_reasons, 'candidate_is_not_synchronous');
    END IF;

    IF v_candidate.replication_lag_ms > v_policy.max_replication_lag_ms THEN
        v_reasons := array_append(
            v_reasons,
            'candidate_replication_lag_exceeds_policy'
        );
    END IF;

    IF v_cluster.current_primary_node_id IS NULL THEN
        v_reasons := array_append(v_reasons, 'current_primary_not_configured');
    ELSE
        SELECT *
        INTO v_primary
        FROM ha.database_nodes
        WHERE cluster_id = p_cluster_id
          AND node_id = v_cluster.current_primary_node_id;

        IF NOT FOUND THEN
            v_reasons := array_append(v_reasons, 'current_primary_not_found');
        ELSE
            SELECT *
            INTO v_primary_health
            FROM ha.latest_node_health
            WHERE cluster_id = p_cluster_id
              AND node_id = v_cluster.current_primary_node_id;

            IF FOUND
               AND v_primary_health.health_status = 'healthy'
               AND v_primary_health.observed_at >=
                   now() - v_policy.max_health_age THEN
                v_reasons := array_append(
                    v_reasons,
                    'current_primary_is_still_healthy'
                );
            END IF;

            IF v_policy.require_old_primary_fenced AND NOT v_primary.fenced THEN
                v_reasons := array_append(
                    v_reasons,
                    'current_primary_has_not_been_fenced'
                );
            END IF;
        END IF;
    END IF;

    SELECT count(*)::INTEGER
    INTO v_healthy_voters
    FROM ha.database_nodes n
    JOIN ha.latest_node_health h
      ON h.cluster_id = n.cluster_id
     AND h.node_id = n.node_id
    WHERE n.cluster_id = p_cluster_id
      AND n.voting_member = TRUE
      AND h.health_status = 'healthy'
      AND h.observed_at >= now() - v_policy.max_health_age;

    IF v_healthy_voters < v_policy.quorum_required THEN
        v_reasons := array_append(
            v_reasons,
            'healthy_voter_quorum_not_reached'
        );
    END IF;

    RETURN QUERY
    SELECT
        cardinality(v_reasons) = 0,
        CASE
            WHEN cardinality(v_reasons) = 0 THEN 'eligible'
            ELSE array_to_string(v_reasons, '; ')
        END,
        v_healthy_voters,
        v_candidate.replication_lag_ms;
END;
$$;


/*
 * Promotion is a transaction-scoped operation.
 *
 * The advisory lock serializes operations for the same cluster. Row locks
 * protect the cluster and affected nodes. The unique partial index prevents
 * two primary nodes. The epoch and fencing token are incremented together.
 */
CREATE OR REPLACE PROCEDURE ha.promote_replica(
    p_cluster_id BIGINT,
    p_candidate_node_id BIGINT,
    p_initiated_by TEXT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_old_primary_id BIGINT;
    v_new_token      BIGINT;
    v_decision       RECORD;
    v_previous_epoch BIGINT;
    v_new_epoch      BIGINT;
BEGIN
    IF p_initiated_by IS NULL OR length(trim(p_initiated_by)) = 0 THEN
        RAISE EXCEPTION 'An initiating actor is required';
    END IF;

    -- The transaction-level lock is automatically released on commit or rollback.
    PERFORM pg_advisory_xact_lock(p_cluster_id);

    SELECT current_primary_node_id, cluster_epoch
    INTO v_old_primary_id, v_previous_epoch
    FROM ha.clusters
    WHERE cluster_id = p_cluster_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Cluster % does not exist', p_cluster_id;
    END IF;

    -- Lock the proposed candidate before evaluating and changing its role.
    PERFORM 1
    FROM ha.database_nodes
    WHERE cluster_id = p_cluster_id
      AND node_id = p_candidate_node_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Candidate node % does not exist', p_candidate_node_id;
    END IF;

    IF v_old_primary_id IS NOT NULL THEN
        PERFORM 1
        FROM ha.database_nodes
        WHERE cluster_id = p_cluster_id
          AND node_id = v_old_primary_id
        FOR UPDATE;
    END IF;

    SELECT *
    INTO v_decision
    FROM ha.evaluate_failover(p_cluster_id, p_candidate_node_id);

    IF NOT COALESCE(v_decision.eligible, FALSE) THEN
        RAISE EXCEPTION 'Failover rejected: %',
            COALESCE(v_decision.reason, 'eligibility evaluation failed')
            USING ERRCODE = '23514';
    END IF;

    -- Demote the previous primary before assigning the new primary role.
    IF v_old_primary_id IS NOT NULL THEN
        UPDATE ha.database_nodes
        SET role = 'replica'
        WHERE cluster_id = p_cluster_id
          AND node_id = v_old_primary_id
          AND role = 'primary';
    END IF;

    UPDATE ha.clusters
    SET current_primary_node_id = p_candidate_node_id,
        cluster_epoch = cluster_epoch + 1,
        fencing_token = fencing_token + 1
    WHERE cluster_id = p_cluster_id
    RETURNING cluster_epoch, fencing_token
    INTO v_new_epoch, v_new_token;

    UPDATE ha.database_nodes
    SET role = 'primary',
        fenced = FALSE,
        fencing_token = v_new_token
    WHERE cluster_id = p_cluster_id
      AND node_id = p_candidate_node_id;

    INSERT INTO ha.failover_events (
        cluster_id,
        old_primary_node_id,
        new_primary_node_id,
        previous_epoch,
        new_epoch,
        fencing_token,
        healthy_voters,
        initiated_by
    )
    VALUES (
        p_cluster_id,
        v_old_primary_id,
        p_candidate_node_id,
        v_previous_epoch,
        v_new_epoch,
        v_new_token,
        v_decision.healthy_voters,
        p_initiated_by
    );
END;
$$;


