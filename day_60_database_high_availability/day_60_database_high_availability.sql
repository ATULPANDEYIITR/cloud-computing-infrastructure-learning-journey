-- Compare the synchronous and asynchronous promotion candidates.
-- The second candidate is expected to fail the synchronous and lag checks.
SELECT
    candidate_node_id,
    evaluation.eligible,
    evaluation.reason,
    evaluation.healthy_voters,
    evaluation.candidate_lag_ms
FROM (
    VALUES
        (102::BIGINT),
        (103::BIGINT)
) AS candidates(candidate_node_id)
CROSS JOIN LATERAL ha.evaluate_failover(
    1,
    candidates.candidate_node_id
) AS evaluation
ORDER BY candidate_node_id;

-- Only the eligible synchronous replica is promoted.
-- The procedure either completes the entire transition or rolls it back.
BEGIN;

CALL ha.promote_replica(
    1,
    102,
    'incident-2026-1042'
);

COMMIT;

-- Verify the single-primary invariant and the new cluster epoch.
SELECT
    c.cluster_name,
    c.current_primary_node_id,
    primary_node.node_name AS current_primary,
    c.cluster_epoch,
    c.fencing_token,
    (
        SELECT count(*)
        FROM ha.database_nodes n
        WHERE n.cluster_id = c.cluster_id
          AND n.role = 'primary'
    ) AS primary_node_count
FROM ha.clusters c
JOIN ha.database_nodes primary_node
    ON primary_node.cluster_id = c.cluster_id
   AND primary_node.node_id = c.current_primary_node_id
WHERE c.cluster_id = 1;

-- Aggregate current node health and replica lag for operational reporting.
WITH latest_health AS (
    SELECT
        n.cluster_id,
        n.node_id,
        n.node_name,
        n.role,
        n.availability_zone,
        n.replication_lag_ms,
        h.health_status,
        h.observed_at
    FROM ha.database_nodes n
    LEFT JOIN ha.latest_node_health h
        ON h.cluster_id = n.cluster_id
       AND h.node_id = n.node_id
    WHERE n.cluster_id = 1
)
SELECT
    cluster_id,
    count(*) AS total_nodes,
    count(*) FILTER (WHERE role = 'primary') AS primary_nodes,
    count(*) FILTER (
        WHERE role = 'replica'
    ) AS replica_nodes,
    count(*) FILTER (
        WHERE health_status = 'healthy'
    ) AS healthy_nodes,
    round(avg(replication_lag_ms), 2) AS average_replication_lag_ms,
    max(replication_lag_ms) AS maximum_replication_lag_ms
FROM latest_health
GROUP BY cluster_id;

-- Failover history provides an auditable record of role transitions.
SELECT
    event_id,
    cluster_id,
    old_primary_node_id,
    new_primary_node_id,
    previous_epoch,
    new_epoch,
    fencing_token,
    healthy_voters,
    initiated_by,
    occurred_at
FROM ha.failover_events
WHERE cluster_id = 1
ORDER BY occurred_at DESC, event_id DESC;

-- CTE-based check of current replica health and policy eligibility.
WITH replica_assessment AS (
    SELECT
        n.node_id,
        n.node_name,
        n.replication_mode,
        n.replication_lag_ms,
        h.health_status,
        h.observed_at
    FROM ha.database_nodes n
    LEFT JOIN ha.latest_node_health h
        ON h.cluster_id = n.cluster_id
       AND h.node_id = n.node_id
    WHERE n.cluster_id = 1
      AND n.role = 'replica'
)
SELECT
    node_name,
    replication_mode,
    replication_lag_ms,
    health_status,
    observed_at,
    CASE
        WHEN health_status <> 'healthy' OR health_status IS NULL
            THEN 'health_check_required'
        WHEN replication_lag_ms > p.max_replication_lag_ms
            THEN 'lag_exceeds_policy'
        WHEN p.require_synchronous_replica
             AND replication_mode <> 'synchronous'
            THEN 'replication_mode_not_eligible'
        ELSE 'passes_basic_replica_checks'
    END AS assessment
FROM replica_assessment
CROSS JOIN ha.failover_policies p
WHERE p.cluster_id = 1
ORDER BY node_name;

-- Health observations and failover events are evidence records.
-- Application roles should receive only the minimum required permissions.
REVOKE UPDATE, DELETE ON ha.health_observations FROM PUBLIC;
REVOKE UPDATE, DELETE ON ha.failover_events FROM PUBLIC;
