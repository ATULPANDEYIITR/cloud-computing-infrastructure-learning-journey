-- Forecasting uses the maximum observed rate as a conservative sample
-- baseline. Percentile estimation is intentionally kept separate because
-- production systems should define their aggregation window explicitly.
CREATE VIEW workload_forecast AS
SELECT
    w.workload_id,
    w.workload_name,
    w.service_name,
    w.current_rps,
    MAX(m.request_rate) AS observed_peak_rps,
    w.current_rps * (1 + w.growth_rate) AS growth_adjusted_rps,
    w.current_rps * (1 + w.growth_rate) * w.safety_factor AS planning_rps
FROM workloads AS w
LEFT JOIN workload_metrics AS m
  ON m.workload_id = w.workload_id
 AND m.observed_at >= CURRENT_TIMESTAMP - INTERVAL '24 hours'
GROUP BY
    w.workload_id,
    w.workload_name,
    w.service_name,
    w.current_rps,
    w.growth_rate,
    w.safety_factor;

-- The effective per-replica throughput is the minimum across four
-- independently modeled resource ceilings.
CREATE VIEW scaling_plan_evaluation AS
WITH resource_limits AS (
    SELECT
        dp.deployment_plan_id,
        w.workload_name,
        i.instance_name,
        p.mode,
        dp.replicas,
        dp.planning_rps,
        i.hourly_cost,
        i.hourly_cost * dp.replicas AS hourly_compute_cost,
        i.hourly_cost * dp.replicas * 730 AS monthly_compute_cost,
        w.latency_budget_ms,
        i.vcpus,
        i.memory_gib,
        i.max_connections,
        i.network_gbps,
        w.cpu_cores_per_request,
        w.memory_gib_per_replica,
        w.connections_per_replica,
        w.network_gbps_per_replica,
        p.cpu_target,
        p.memory_target,
        p.connection_target,
        p.network_target,
        p.requests_per_core_second,
        p.maximum_replicas,
        p.minimum_replicas,
        p.maximum_vertical_vcpus,
        p.maximum_vertical_memory_gib,
        i.vcpus * p.cpu_target
            / (w.cpu_cores_per_request * 1.25) AS cpu_capacity_rps,
        i.memory_gib * p.memory_target
            / w.memory_gib_per_replica AS memory_capacity_rps,
        i.max_connections * p.connection_target
            / GREATEST(w.connections_per_replica, 1) AS connection_capacity_rps,
        i.network_gbps * p.network_target
            / GREATEST(w.network_gbps_per_replica, 0.001) AS network_capacity_rps
    FROM deployment_plans AS dp
    JOIN workloads AS w ON w.workload_id = dp.workload_id
    JOIN instance_types AS i ON i.instance_type_id = dp.instance_type_id
    JOIN scaling_policies AS p ON p.policy_id = dp.policy_id
),
capacity AS (
    SELECT
        resource_limits.*,
        LEAST(
            cpu_capacity_rps,
            memory_capacity_rps,
            connection_capacity_rps,
            network_capacity_rps
        ) * replicas AS estimated_capacity_rps,
        planning_rps * cpu_cores_per_request / (vcpus * replicas)
            AS estimated_cpu_utilization,
        memory_gib_per_replica / memory_gib
            AS estimated_memory_utilization,
        connections_per_replica::NUMERIC / max_connections
            AS estimated_connection_utilization,
        network_gbps_per_replica / network_gbps
            AS estimated_network_utilization
    FROM resource_limits
)
SELECT
    deployment_plan_id,
    workload_name,
    instance_name,
    mode,
    replicas,
    planning_rps,
    estimated_capacity_rps,
    hourly_compute_cost,
    monthly_compute_cost,
    estimated_cpu_utilization,
    estimated_memory_utilization,
    estimated_connection_utilization,
    estimated_network_utilization,
    CASE
        WHEN planning_rps > estimated_capacity_rps THEN 'throughput_capacity_exceeded'
        WHEN estimated_cpu_utilization > cpu_target THEN 'cpu_target_exceeded'
        WHEN estimated_memory_utilization > memory_target THEN 'memory_target_exceeded'
        WHEN estimated_connection_utilization > connection_target THEN 'connection_target_exceeded'
        WHEN estimated_network_utilization > network_target THEN 'network_target_exceeded'
        WHEN mode = 'horizontal' AND replicas > maximum_replicas THEN 'replica_limit_exceeded'
        WHEN mode = 'vertical' AND (
            vcpus > maximum_vertical_vcpus
            OR memory_gib > maximum_vertical_memory_gib
        ) THEN 'vertical_limit_exceeded'
        ELSE 'feasible_under_modeled_constraints'
    END AS evaluation
FROM capacity;

-- Inspect current plans and resource ceilings.
SELECT *
FROM scaling_plan_evaluation
ORDER BY workload_name;

-- Compare horizontal deployment cost as replica count changes.
SELECT
    i.instance_name,
    candidate.replicas,
    i.hourly_cost * candidate.replicas AS hourly_compute_cost,
    i.hourly_cost * candidate.replicas * 730 AS monthly_compute_cost
FROM instance_types AS i
CROSS JOIN generate_series(2, 12) AS candidate(replicas)
WHERE i.instance_name = 'compute-medium'
ORDER BY candidate.replicas;

-- Identify observed pressure requiring workload review.
SELECT
    w.workload_name,
    m.observed_at,
    m.request_rate,
    m.cpu_utilization,
    m.memory_utilization,
    m.connection_utilization,
    m.network_utilization,
    m.p95_latency_ms,
    m.error_rate
FROM workload_metrics AS m
JOIN workloads AS w ON w.workload_id = m.workload_id
WHERE m.cpu_utilization >= 0.70
   OR m.memory_utilization >= 0.75
   OR m.connection_utilization >= 0.70
   OR m.network_utilization >= 0.70
   OR m.p95_latency_ms > w.latency_budget_ms
ORDER BY m.observed_at DESC, w.workload_name;

-- Record a proposed scale-out event inside a transaction. The check
-- constraint ensures that a scale-out request increases the replica count.
INSERT INTO scaling_events (
    deployment_plan_id,
    previous_replicas,
    requested_replicas,
    action,
    reason,
    accepted
)
SELECT
    dp.deployment_plan_id,
    dp.replicas,
    dp.replicas + 1,
    CASE
        WHEN dp.replicas < p.maximum_replicas THEN 'scale_out'
        ELSE 'blocked'
    END,
    CASE
        WHEN dp.replicas < p.maximum_replicas
            THEN 'Observed demand exceeds the configured scale-out threshold'
        ELSE 'Maximum replica count reached'
    END,
    dp.replicas < p.maximum_replicas
FROM deployment_plans AS dp
JOIN scaling_policies AS p ON p.policy_id = dp.policy_id
WHERE dp.status = 'proposed'
  AND dp.workload_id = (
      SELECT workload_id FROM workloads WHERE workload_name = 'checkout-api'
  );

-- Governance systems should compare event history with current deployment
-- state. This query exposes recorded actions that have not been applied.
SELECT
    se.scaling_event_id,
    dp.deployment_plan_id,
    w.workload_name,
    se.previous_replicas,
    se.requested_replicas,
    se.action,
    se.accepted,
    dp.replicas AS currently_configured_replicas
FROM scaling_events AS se
JOIN deployment_plans AS dp
  ON dp.deployment_plan_id = se.deployment_plan_id
JOIN workloads AS w
  ON w.workload_id = dp.workload_id
WHERE se.accepted = TRUE
  AND se.requested_replicas <> dp.replicas
ORDER BY se.event_time DESC;

COMMIT;
