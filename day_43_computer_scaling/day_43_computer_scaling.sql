-- PostgreSQL 14+
-- Compute scaling, resource capacity, workload forecasting, and cost planning.
--
-- This model uses hypothetical capacity measurements and hourly rates.
-- A real deployment should load benchmark results and current provider pricing.
--
-- The schema separates hardware specifications, workload demand,
-- deployment choices, observed metrics, and scaling policy.

BEGIN;

DROP VIEW IF EXISTS scaling_plan_evaluation;
DROP VIEW IF EXISTS workload_forecast;
DROP TABLE IF EXISTS scaling_events CASCADE;
DROP TABLE IF EXISTS workload_metrics CASCADE;
DROP TABLE IF EXISTS deployment_plans CASCADE;
DROP TABLE IF EXISTS workloads CASCADE;
DROP TABLE IF EXISTS instance_types CASCADE;
DROP TABLE IF EXISTS scaling_policies CASCADE;

CREATE TABLE instance_types (
    instance_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_name TEXT NOT NULL UNIQUE,
    vcpus INTEGER NOT NULL CHECK (vcpus > 0),
    memory_gib NUMERIC(10, 2) NOT NULL CHECK (memory_gib > 0),
    max_connections INTEGER NOT NULL CHECK (max_connections > 0),
    network_gbps NUMERIC(10, 3) NOT NULL CHECK (network_gbps > 0),
    hourly_cost NUMERIC(12, 4) NOT NULL CHECK (hourly_cost >= 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE workloads (
    workload_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_name TEXT NOT NULL UNIQUE,
    service_name TEXT NOT NULL,
    current_rps NUMERIC(14, 3) NOT NULL CHECK (current_rps >= 0),
    growth_rate NUMERIC(8, 5) NOT NULL DEFAULT 0
        CHECK (growth_rate >= 0),
    safety_factor NUMERIC(6, 3) NOT NULL DEFAULT 1.20
        CHECK (safety_factor >= 1),
    cpu_cores_per_request NUMERIC(12, 8) NOT NULL
        CHECK (cpu_cores_per_request > 0),
    memory_gib_per_replica NUMERIC(10, 3) NOT NULL
        CHECK (memory_gib_per_replica > 0),
    connections_per_replica INTEGER NOT NULL
        CHECK (connections_per_replica >= 0),
    network_gbps_per_replica NUMERIC(10, 4) NOT NULL
        CHECK (network_gbps_per_replica >= 0),
    latency_budget_ms NUMERIC(10, 2) NOT NULL
        CHECK (latency_budget_ms > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE scaling_policies (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_name TEXT NOT NULL UNIQUE,
    mode TEXT NOT NULL CHECK (mode IN ('vertical', 'horizontal')),
    minimum_replicas INTEGER NOT NULL CHECK (minimum_replicas >= 1),
    maximum_replicas INTEGER NOT NULL,
    cpu_target NUMERIC(5, 4) NOT NULL CHECK (cpu_target > 0 AND cpu_target <= 1),
    memory_target NUMERIC(5, 4) NOT NULL
        CHECK (memory_target > 0 AND memory_target <= 1),
    connection_target NUMERIC(5, 4) NOT NULL
        CHECK (connection_target > 0 AND connection_target <= 1),
    network_target NUMERIC(5, 4) NOT NULL
        CHECK (network_target > 0 AND network_target <= 1),
    requests_per_core_second NUMERIC(12, 4) NOT NULL
        CHECK (requests_per_core_second > 0),
    cooldown_seconds INTEGER NOT NULL CHECK (cooldown_seconds >= 0),
    scale_out_threshold NUMERIC(5, 4) NOT NULL
        CHECK (scale_out_threshold > 0 AND scale_out_threshold <= 1),
    scale_in_threshold NUMERIC(5, 4) NOT NULL
        CHECK (scale_in_threshold >= 0 AND scale_in_threshold < 1),
    maximum_vertical_vcpus INTEGER NOT NULL CHECK (maximum_vertical_vcpus > 0),
    maximum_vertical_memory_gib NUMERIC(10, 2) NOT NULL
        CHECK (maximum_vertical_memory_gib > 0),
    CHECK (maximum_replicas >= minimum_replicas),
    CHECK (scale_in_threshold < scale_out_threshold)
);

CREATE TABLE deployment_plans (
    deployment_plan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_id BIGINT NOT NULL REFERENCES workloads(workload_id),
    instance_type_id BIGINT NOT NULL REFERENCES instance_types(instance_type_id),
    policy_id BIGINT NOT NULL REFERENCES scaling_policies(policy_id),
    replicas INTEGER NOT NULL CHECK (replicas >= 1),
    planning_rps NUMERIC(14, 3) NOT NULL CHECK (planning_rps >= 0),
    status TEXT NOT NULL DEFAULT 'proposed'
        CHECK (status IN ('proposed', 'approved', 'active', 'retired')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (status <> 'active' OR replicas >= 1)
);

CREATE TABLE workload_metrics (
    metric_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_id BIGINT NOT NULL REFERENCES workloads(workload_id),
    observed_at TIMESTAMPTZ NOT NULL,
    request_rate NUMERIC(14, 3) NOT NULL CHECK (request_rate >= 0),
    cpu_utilization NUMERIC(8, 5) NOT NULL
        CHECK (cpu_utilization >= 0),
    memory_utilization NUMERIC(8, 5) NOT NULL
        CHECK (memory_utilization >= 0),
    connection_utilization NUMERIC(8, 5) NOT NULL
        CHECK (connection_utilization >= 0),
    network_utilization NUMERIC(8, 5) NOT NULL
        CHECK (network_utilization >= 0),
    p95_latency_ms NUMERIC(12, 3) NOT NULL CHECK (p95_latency_ms >= 0),
    error_rate NUMERIC(8, 5) NOT NULL CHECK (error_rate >= 0 AND error_rate <= 1),
    UNIQUE (workload_id, observed_at)
);

CREATE TABLE scaling_events (
    scaling_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deployment_plan_id BIGINT NOT NULL
        REFERENCES deployment_plans(deployment_plan_id),
    event_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    previous_replicas INTEGER NOT NULL CHECK (previous_replicas >= 1),
    requested_replicas INTEGER NOT NULL CHECK (requested_replicas >= 1),
    action TEXT NOT NULL
        CHECK (action IN ('scale_out', 'scale_in', 'blocked', 'no_change')),
    reason TEXT NOT NULL,
    accepted BOOLEAN NOT NULL,
    CHECK (
        (action = 'scale_out' AND requested_replicas > previous_replicas)
        OR (action = 'scale_in' AND requested_replicas < previous_replicas)
        OR (action IN ('blocked', 'no_change'))
    )
);

CREATE INDEX idx_metrics_workload_time
    ON workload_metrics (workload_id, observed_at DESC);

CREATE INDEX idx_deployment_workload_status
    ON deployment_plans (workload_id, status);

CREATE INDEX idx_scaling_events_plan_time
    ON scaling_events (deployment_plan_id, event_time DESC);

